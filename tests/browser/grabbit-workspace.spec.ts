import {expect, test} from '@playwright/test'

test('Grabbit workspace keeps video, options, and trimming readable at desktop and compact sizes', async ({page}) => {
	await page.setViewportSize({width: 1600, height: 1000})
	await page.goto('/?scenario=single-normal&mockStep=formats&locale=fr&theme=dark')
	await expect(page.getByTestId('download-options-panel')).toBeVisible()
	await expect(page.getByTestId('app-footer')).toHaveCount(0)
	await expect(page.getByTestId('quality-presets').getByRole('button')).toHaveCount(2)
	await expect(page.getByTestId('advanced-quality-presets')).not.toBeVisible()
	await page.locator('.grabbit-more-options > summary').click()
	await expect(page.getByTestId('advanced-quality-presets')).toBeVisible()
	await expect(page.getByTestId('advanced-quality-presets').getByRole('button')).toHaveCount(3)
	await page.locator('.grabbit-more-options > summary').click()
	const summary = page.getByTestId('detected-video-panel')
	const options = page.getByTestId('download-options-panel')
	const trim = page.getByTestId('clip-range-section')
	await expect(summary).toBeVisible()
	const summaryBox = await summary.boundingBox()
	const optionsBox = await options.boundingBox()
	const trimBox = await trim.boundingBox()
	expect(summaryBox && optionsBox && trimBox).toBeTruthy()
	if (!summaryBox || !optionsBox || !trimBox) return
	expect(Math.abs(summaryBox.y - optionsBox.y)).toBeLessThan(3)
	expect(optionsBox.x).toBeGreaterThan(summaryBox.x + summaryBox.width)
	expect(trimBox.y).toBeGreaterThan(summaryBox.y + summaryBox.height)

	await page.getByTestId('clip-range-custom').click()
	const startSlider = page.getByTestId('clip-start-slider')
	await startSlider.focus()
	await page.keyboard.press('ArrowRight')
	await expect(page.getByTestId('clip-start')).not.toHaveValue('00:00')
	await expect(page.getByTestId('clip-summary')).toBeVisible()

	await page.setViewportSize({width: 760, height: 800})
	await expect(page.getByTestId('app-footer')).toHaveCount(0)
	await expect(options).toBeVisible()
	const overflow = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth)
	expect(overflow).toBe(false)
	await expect(page.getByTestId('btn-download')).toBeEnabled()
	await page.getByRole('tab', {name: /Téléchargements/}).click()
	await expect(page.getByTestId('queue-manager-tab')).toBeVisible()
	await page.getByRole('tab', {name: 'URL', exact: true}).click()
	await expect(page.getByTestId('clip-start')).not.toHaveValue('00:00')
})
